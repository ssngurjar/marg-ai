"""Generate docs/code-map.md: every module under app/, its classes, and what each one does.

Run `.venv/bin/python -m scripts.code_map` after adding or renaming a module; the unit test
`tests/unit/test_code_map.py` fails while the committed map is out of date.
"""

import ast
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
APP_ROOT = REPO_ROOT / "app"
MAP_PATH = REPO_ROOT / "docs" / "code-map.md"

HEADER = """# Code map

Generated by `scripts/code_map.py` from the code itself; don't edit by hand. Conventions are in
CLAUDE.md §7 ("Code organisation"). Each row: the module, the classes it defines, and the first
line of the module's docstring.

"""


@dataclass(frozen=True, slots=True)
class ModuleEntry:
    path: str  # relative to the repo, e.g. app/worker/turn_processor.py
    classes: list[str]
    summary: str


def summarise(path: Path) -> ModuleEntry:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    docstring = ast.get_docstring(tree) or ""
    first_line = docstring.strip().splitlines()[0] if docstring.strip() else ""
    classes = [
        node.name
        for node in tree.body
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_")
    ]
    return ModuleEntry(
        path=path.relative_to(REPO_ROOT).as_posix(), classes=classes, summary=first_line
    )


def render() -> str:
    modules = sorted(
        path
        for path in APP_ROOT.rglob("*.py")
        if "__pycache__" not in path.parts and path.name != "__init__.py"
    )
    sections: dict[str, list[ModuleEntry]] = {}
    for path in modules:
        entry = summarise(path)
        area = "/".join(Path(entry.path).parts[1:-1]) or "app"
        sections.setdefault(area, []).append(entry)
    lines = [HEADER.rstrip(), ""]
    for area, entries in sections.items():
        lines.extend([f"## `{area}`", "", "| Module | Classes | What it does |", "|---|---|---|"])
        for entry in entries:
            classes = ", ".join(f"`{name}`" for name in entry.classes) or "—"
            summary = entry.summary.replace("|", "\\|")
            lines.append(f"| `{Path(entry.path).name}` | {classes} | {summary} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    MAP_PATH.write_text(render(), encoding="utf-8")
    sys.stdout.write(f"wrote {MAP_PATH.relative_to(REPO_ROOT)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

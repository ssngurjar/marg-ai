"""Fetch every district of India from the Local Government Directory (LGD, Ministry of Panchayati
Raj, maintained by NIC) and write `app/constants/lgd_districts.py` (critic review D4, 2026-11-01).

`.venv/bin/python -m scripts.fetch_districts` calls LGD's web service: the state list, then each
state's districts (POST, form body). The module it writes records the source and the date; it is
the only copy of the list in the repository and is never edited by hand.
"""

import asyncio
import sys
import unicodedata
from pathlib import Path
from typing import Final

import httpx
from pydantic import BaseModel, ConfigDict, Field, TypeAdapter

from app.core.clock import SystemClock

SERVICE: Final = "https://lgdirectory.gov.in/webservices/lgdws"
OUTPUT: Final = Path(__file__).resolve().parents[1] / "app" / "constants" / "lgd_districts.py"
TIMEOUT_SECONDS: Final = 30.0


class LgdState(BaseModel):
    model_config = ConfigDict(frozen=True, extra="ignore")

    code: int = Field(alias="stateCode")
    name: str = Field(alias="stateNameEnglish")


class LgdDistrictRow(BaseModel):
    model_config = ConfigDict(frozen=True, extra="ignore")

    code: int = Field(alias="districtCode")
    name: str = Field(alias="districtNameEnglish")
    local_name: str | None = Field(alias="districtNameLocal")


STATES: Final = TypeAdapter(list[LgdState])
DISTRICTS: Final = TypeAdapter(list[LgdDistrictRow])


def _devanagari(name: str | None) -> str | None:
    """LGD's local name only when it's in Devanagari (older rows repeat the English in capitals)."""
    if name is None:
        return None
    cleaned = unicodedata.normalize("NFC", name.strip())
    has_devanagari = any("ऀ" <= letter <= "ॿ" for letter in cleaned)
    return cleaned if has_devanagari else None


async def _fetch() -> list[tuple[int, str, str, str | None]]:
    rows: list[tuple[int, str, str, str | None]] = []
    async with httpx.AsyncClient(timeout=TIMEOUT_SECONDS) as client:
        response = await client.post(f"{SERVICE}/stateList", content=b"")
        response.raise_for_status()
        for state in STATES.validate_json(response.content):
            state_name = state.name.strip()
            reply = await client.post(
                f"{SERVICE}/districtList", data={"stateCode": str(state.code)}
            )
            reply.raise_for_status()
            for district in DISTRICTS.validate_json(reply.content):
                local = _devanagari(district.local_name)
                rows.append((district.code, district.name.strip(), state_name, local))
    return sorted(rows, key=lambda row: (row[2], row[1]))


def _module(rows: list[tuple[int, str, str, str | None]], retrieved: str) -> str:
    year, month, day = (int(part) for part in retrieved.split("-"))
    lines = [
        '"""Every district of India, as the Local Government Directory (LGD) lists them.',
        "",
        "Generated by `scripts/fetch_districts.py` from LGD's web service (Ministry of Panchayati",
        "Raj, maintained by NIC); never edited by hand. Run it again to refresh. LGD's own site:",
        "https://lgdirectory.gov.in/ (critic review D4, 2026-11-01).",
        '"""',
        "",
        "from datetime import date",
        "from typing import Final",
        "",
        "from app.domain.models.district import LgdDistrict",
        "",
        f'SOURCE_URL: Final = "{SERVICE}/districtList"',
        f"RETRIEVED_ON: Final = date({year}, {month}, {day})",
        "DISTRICTS: Final[tuple[LgdDistrict, ...]] = (",
    ]
    for code, name, state, local in rows:
        lines.append(f"    LgdDistrict({code}, {name!r}, {state!r}, {local!r}),")
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> None:
    rows = asyncio.run(_fetch())
    retrieved = SystemClock().now().date().isoformat()
    OUTPUT.write_text(_module(rows, retrieved), encoding="utf-8")
    sys.stdout.write(f"{len(rows)} districts written to {OUTPUT}\n")


if __name__ == "__main__":
    main()
